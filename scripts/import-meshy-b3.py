"""Convert the reviewed B3 GLB, preserving its actual texture and projected UVs.
Usage: python3 scripts/import-meshy-b3.py model.glb
Offline dependencies: trimesh==5.2.0 pillow numpy.
The masks below are specific to Meshy task 01a1a87e-d709-73c8-b5d8-3fe935a944b8.
"""
import base64
import hashlib
import io
import json
import sys
from pathlib import Path

import numpy as np
import trimesh

source = Path(sys.argv[1])
scene = trimesh.load(source, force="scene")
assert len(scene.geometry) == 1, "Review transforms and masks for a different asset"
original = scene.to_mesh()
uv = original.visual.uv.copy()
texture = original.visual.material.baseColorTexture.convert("RGB")
texture.thumbnail((1024, 1024))
image = io.BytesIO()
texture.save(image, format="JPEG", quality=90)
v = original.vertices
original.vertices = np.column_stack((-v[:, 2], v[:, 1], v[:, 0]))
c = original.triangles_center
x, y, z = c.T
dorsal = (abs(x) < .13) & (y > .135) & (z > -.46) & (z < -.18)
ventral = (abs(x) < .13) & (y < -.135) & (z > -.16) & (z < .10)
tail = (abs(x) < .13) & (z > .67) & (y > -.01) & (y < .12)
prop = (abs(x) > .18) & (abs(x) < .40) & (z < -.60) & (z > -.69) & (y > -.115)
barrels = (dorsal & (z < -.40)) | (tail & (z > .77)) | (ventral & (y < -.235))
wing = abs(x) > .42
masks = [dorsal, tail, ventral, prop & (x < 0), prop & (x >= 0), wing]
# One common uniform scale preserves the reference silhouette. Ground contact is
# calibrated to the existing B3 gear; actor units are applied by the client.
scale = 11.3 / np.ptp(original.vertices[:, 0])
offset = np.array([0, -1.45 - original.vertices[:, 1].min() * scale, 0])
parts = []
for name, mask, pivot, budget in [
    ("body", ~np.logical_or.reduce(masks), [0, 0, 0], 4200),
    ("wing", wing, [0, 0, 0], 0),
    ("dorsal", dorsal, [0, .18, -.29], 300),
    ("tail", tail, [0, .045, .72], 220),
    ("ventral", ventral, [0, -.18, -.03], 380),
    ("propLeft", masks[3], [-.28, 0, -.635], 200),
    ("propRight", masks[4], [.28, 0, -.635], 200),
]:
    mask = mask & ~barrels
    mesh = original.submesh([np.flatnonzero(mask)], append=True)
    # Preserve Meshy's original UV seams and topology: geometric decimation
    # without seam constraints corrupts this atlas. Compact indexed attributes
    # below instead of baking random or per-face replacement colors.
    points = mesh.vertices
    projected_uv = mesh.visual.uv.copy()
    # trimesh converts glTF UVs to bottom-left; restore glTF top-left for flipY=false.
    projected_uv[:, 1] = 1 - projected_uv[:, 1]
    pivot = np.asarray(pivot) * scale + offset if name not in ["body", "wing"] else np.zeros(3)
    parts.append({"name": name, "pivot": np.round(pivot, 5).tolist(),
                  "positions": np.round(points * scale + offset - pivot, 5).flatten().tolist(),
                  "uv": np.round(projected_uv, 6).flatten().tolist(), "indices": mesh.faces.flatten().tolist()})
contact = min(np.asarray(p["positions"]).reshape(-1, 3)[:, 1].min() + p["pivot"][1] for p in parts)
for p in parts:
    if p["name"] in ["body", "wing"]:
        coords = np.asarray(p["positions"]).reshape(-1, 3)
        coords[:, 1] += -1.45 - contact
        p["positions"] = np.round(coords, 5).flatten().tolist()
    else:
        p["pivot"][1] += -1.45 - contact
stats = [{"name": p["name"], "triangles": len(p["indices"]) // 3} for p in parts]
for p in parts:
    positions = np.asarray(p.pop("positions"))
    uvs = np.asarray(p.pop("uv"))
    indices = np.asarray(p.pop("indices"))
    assert indices.max() < 65536
    p["positions"] = base64.b64encode(np.round(positions / .0005).astype("<i2").tobytes()).decode()
    p["uv"] = base64.b64encode(np.round(np.clip(uvs, 0, 1) * 65535).astype("<u2").tobytes()).decode()
    p["indices"] = base64.b64encode(indices.astype("<u2").tobytes()).decode()
data = {"parts": parts, "texture": "data:image/jpeg;base64," + base64.b64encode(image.getvalue()).decode()}
Path("src/meshy-b3-data.js").write_text(
    "// Generated by scripts/import-meshy-b3.py; Meshy 01a1a87e-d709-73c8-b5d8-3fe935a944b8.\n"
    + "export const B3_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(json.dumps({"sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                  "source_triangles": len(original.faces), "parts": stats,
                  "texture_bytes": len(image.getvalue())}))
