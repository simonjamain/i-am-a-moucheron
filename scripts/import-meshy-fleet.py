"""Bake reviewed Meshy fleet GLBs to shared colored triangles (offline only).
Requires trimesh==5.2.0, fast-simplification==0.2.0, scipy, pillow, shapely.
Usage: python scripts/import-meshy-fleet.py NAME SOURCE.glb
Orientations and part boundaries are specific to the documented Meshy tasks.
"""
import hashlib
import json
import sys
from pathlib import Path
import numpy as np
import trimesh
from scipy.spatial import cKDTree

name, path = sys.argv[1:]
source = Path(path)
scene = trimesh.load(source, force='scene')
original = scene.to_mesh()
print('source', name, len(original.faces), original.bounds.tolist())
# All four reviewed exports point toward -X, with span/width along Z.
original.vertices = np.column_stack((-original.vertices[:, 2], original.vertices[:, 1], original.vertices[:, 0]))
colors = original.visual.to_color().vertex_colors[:, :3]
width, height, length, floor = {
 'stuka': (7.7, 1.9, 4.6, -1.05),
 'spitfire': (6.2, 1.6, 3.8, -1.05),
 'tank': (3.55, 1.45, 4.1, -.8),
 'flaktruck': (2.3, 2.4, 9.0, -.8),
}[name]
v = original.vertices.copy()
for axis, size in [(0,width),(1,height),(2,length)]:
 v[:,axis] = (v[:,axis] - v[:,axis].min()) / np.ptp(v[:,axis]) * size
v[:,0] -= width/2
v[:,1] += floor
v[:,2] -= length/2
if name == 'flaktruck':
 # Place the narrow coupling on the existing animated trailer pivot, z=-0.7.
 raw = original.vertices[:,2]
 split = -.19
 v[:,2] = np.where(raw < split, -4.3 + (raw-raw.min())/(split-raw.min())*3.6,
                   -.7 + (raw-split)/(raw.max()-split)*5.4)
original.vertices = v
source_tree = cKDTree(v)
original.merge_vertices(merge_tex=True, merge_norm=True)
parts = []
stats = []
if name == 'flaktruck':
 meshes = [('body', original.slice_plane([0,0,-.7],[0,0,-1]), 1500),
           ('trailer', original.slice_plane([0,0,-.7],[0,0,1]), 1500)]
else:
 meshes = [('body', original, 3000)]
for part_name, base, budget in meshes:
 mesh = base.simplify_quadric_decimation(face_count=budget)
 centers = mesh.triangles_center
 rgb = colors[source_tree.query(centers)[1]].astype(float)
 olive = (rgb[:,1] > rgb[:,2]*1.15) & (rgb[:,0] < rgb[:,1]*1.03) & (rgb[:,0] > rgb[:,2]*1.1) & (rgb[:,1]>45)
 labels = np.full(len(mesh.faces),part_name,dtype='<U10')
 if name in ['stuka','spitfire']:
  labels[(abs(centers[:,0])>.62) & (centers[:,2]<.7) & (centers[:,1]>-.45)]='wing'
 for label in sorted(set(labels)):
  for paint in [False,True]:
   mask = (labels==label)&(olive==paint)
   if not mask.any(): continue
   pivot = np.array([0,0,-.7]) if label=='trailer' else np.zeros(3)
   points = (mesh.triangles[mask]-pivot).reshape(-1,3)
   part={'part':label,'paint':paint,'positions':np.round(points,5).flatten().tolist()}
   if not paint:
    srgb=rgb[mask]/255
    linear=np.where(srgb<=.04045,srgb/12.92,((srgb+.055)/1.055)**2.4)
    part['colors']=np.round(np.repeat(linear,3,axis=0),4).flatten().tolist()
   parts.append(part)
 stats.append({'part':part_name,'triangles':len(mesh.faces)})
result='// Generated by scripts/import-meshy-fleet.py; provenance: docs/meshy-fleet.md.\n'
result+='export const PARTS = '+json.dumps(parts,separators=(',',':'))+';\n'
Path('src/meshy-'+name+'-data.js').write_text(result)
print(json.dumps({'name':name,'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'source_triangles':sum(len(g.faces) for g in scene.geometry.values()),'parts':stats,'bytes':len(result)}))
