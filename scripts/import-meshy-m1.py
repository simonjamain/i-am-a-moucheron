"""Bake the M1 Meshy GLB into static low-poly browser geometry.
Usage: python3 scripts/import-meshy-m1.py path/to/m1.glb
Offline requirements: trimesh==5.2.0 fast-simplification==0.2.0 scipy pillow.
No Python, image decoder or GLTF loader is needed at runtime.
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import trimesh
from scipy.spatial import cKDTree

source = Path(sys.argv[1])
scene = trimesh.load(source, force="scene")
assert len(scene.geometry) == 1, "Review transforms and parts before importing another model"
original = scene.to_mesh()
colors = original.visual.to_color().vertex_colors[:, :3]
# Meshy nose is -X, span is Z. Rotate into the game's nose -Z / span X.
v = original.vertices
original.vertices = np.column_stack((-v[:, 2], v[:, 1], v[:, 0]))
original.merge_vertices(merge_tex=True, merge_norm=True)
# Sample the original texture before simplification; mesh merging changes UV seams.
source_mesh = scene.to_mesh()
source_vertices = np.column_stack((-source_mesh.vertices[:, 2], source_mesh.vertices[:, 1], source_mesh.vertices[:, 0]))
tree = cKDTree(source_vertices)
mesh = original.simplify_quadric_decimation(face_count=2800)
centers = mesh.triangles_center
rgb = colors[tree.query(centers)[1]].astype(float)
# Keep the illustrated olive paint separate for per-aircraft liveries. The
# remaining texture colors are baked per triangle, avoiding texture downloads.
olive = (rgb[:, 0] < 175) & (rgb[:, 1] > rgb[:, 2] * 1.12) & (rgb[:, 0] > rgb[:, 2] * 1.08) & (rgb[:, 0] < rgb[:, 1] * 1.25)
# Detach the propeller plane, including its hub. Keep the cowling behind it.
prop = centers[:, 2] < -0.73
wing = (~prop) & (abs(centers[:, 0]) > 0.22) & (centers[:, 1] > 0.065) & (centers[:, 2] > -0.42) & (centers[:, 2] < 0.1)
# Match the existing span and parked ground contact; preserve the generated proportions.
scale = 5.6 / np.ptp(mesh.vertices[:, 0])
mesh.vertices *= scale
mesh.vertices[:, 1] += -1.05 - mesh.vertices[:, 1].min()
mesh.vertices[:, 2] -= (mesh.vertices[:, 2].min() + mesh.vertices[:, 2].max()) / 2
parts = []
for name, mask in [("body", ~prop & ~wing), ("wing", wing), ("prop", prop)]:
    pivot = mesh.triangles_center[prop].mean(axis=0) if name == "prop" else np.zeros(3)
    if name == "prop":
        pivot[0] = 0
    for paint in [False, True]:
        selected = np.flatnonzero(mask & (olive == paint))
        if not len(selected):
            continue
        points = (mesh.triangles[selected] - pivot).reshape(-1, 3)
        part = {"part": name, "paint": paint, "pivot": np.round(pivot, 5).tolist(), "positions": np.round(points, 5).flatten().tolist()}
        if not paint:
            # Texture pixels are sRGB; Three vertex colors use linear RGB.
            srgb = rgb[selected] / 255
            linear = np.where(srgb <= .04045, srgb / 12.92, ((srgb + .055) / 1.055) ** 2.4)
            part["colors"] = np.round(np.repeat(linear, 3, axis=0), 4).flatten().tolist()
        parts.append(part)
result = "// Generated by scripts/import-meshy-m1.py; Meshy task 01a1a800-d23f-700f-a4c7-6f5cff0ed1fc.\n"
result += "export const M1_PARTS = " + json.dumps(parts, separators=(",", ":")) + ";\n"
Path("src/meshy-m1-data.js").write_text(result)
print(json.dumps({"source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(), "source_triangles": len(original.faces), "triangles": len(mesh.faces), "parts": len(parts), "bytes": len(result)}))
