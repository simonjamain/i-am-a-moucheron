"""Import the four original textured Meshy T-01 GLBs as standalone offline JS assets.

Usage:
  python3 scripts/import-meshy-t01.py --sources DIR --output src [--texture-size 1024]

Expected source filenames: socle.glb, tete.glb, canon.glb, capteur.glb.
Safeguards: pinned approved source hashes, exactly one 3D mesh/part,
UV + PBR base color atlas present; source files remain immutable.
The original Meshy UVs and color design are retained. Its 2K image is
resampled as a 1K WebP runtime copy to keep the miniature fast in browser.
"""
import argparse
import base64
import hashlib
import io
import json
from pathlib import Path

import numpy as np
import trimesh
from PIL import Image

TASKS = {
    'socle': ('01a1b589-f91a-74d7-9cfd-af1e09fc7fcf', 'cadf161689f2adb53caa3ac8c8968d5393a6f53fface5cc9b6cc07dfe889c695'),
    'tete': ('01a1b58b-8015-7247-b17b-351c9946a143', '105bef2d800728dd5e208a404a95f4e45b8a66b428c46b99f91efc90e6779472'),
    'canon': ('01a1b58b-8f11-7588-92a6-80bdb540bbe5', 'b29849fbb1b7bb3e9d837462977d6934808e59535f13340e452684cd3eeaa743'),
    'capteur': ('01a1b58b-9c0b-74a9-bb5c-269a36d9169c', '5f5882e848d834f8b3e9bdba71ab63f0c67e74b632909f433021c38908f1467c'),
}


def encode(kind, source, texture_size):
    task, expected_hash = TASKS[kind]
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if digest != expected_hash:
        raise ValueError(f'{kind}: rejected original GLB sha256 {digest} != approved {expected_hash}')
    scene = trimesh.load(source, force='scene', process=False)
    if len(scene.geometry) != 1:
        raise ValueError(f'{kind}: expected 1 mesh, got {len(scene.geometry)}')
    mesh = next(iter(scene.geometry.values()))
    uv = np.asarray(mesh.visual.uv, dtype=np.float64)
    vertices = np.asarray(mesh.vertices, dtype=np.float64)
    indices = np.asarray(mesh.faces, dtype=np.int64)
    if not (uv.shape == (len(vertices), 2) and len(indices) > 100 and indices.ndim == 2 and indices.shape[1] == 3):
        raise ValueError(f'{kind}: no reliable UV indexed triangle geometry')
    if not np.isfinite(vertices).all() or not np.isfinite(uv).all() or not (0 <= indices).all() or np.max(indices) >= len(vertices):
        raise ValueError(f'{kind}: invalid vertex / triangle data')
    if len(vertices) > 65535 or np.max(np.abs(vertices)) > 16:
        raise ValueError(f'{kind}: unsupported 16-bit vertex positions')
    if np.min(uv) < -0.001 or np.max(uv) > 1.001:
        raise ValueError(f'{kind}: UV outside unit atlas')
    tex = getattr(mesh.visual.material, 'baseColorTexture', None)
    if not isinstance(tex, Image.Image):
        raise ValueError(f'{kind}: missing embedded Meshy PBR base color texture')
    # glTF UV coordinates are top-down in a flipY=false Three.js texture, and
    # trimesh exposes bottom-up UVs. Match existing import-meshy-castor.py.
    uv = np.clip(uv, 0, 1)
    uv[:, 1] = 1 - uv[:, 1]
    pos16 = np.rint(vertices / 0.0005).astype('<i2')
    uv16 = np.rint(uv * 65535).astype('<u2')
    face16 = indices.astype('<u2').ravel()
    resized = tex.convert('RGB').resize((texture_size, texture_size), Image.Resampling.LANCZOS)
    buf = io.BytesIO()
    resized.save(buf, format='WEBP', quality=86, method=6)
    texture_bytes = buf.getvalue()
    enc = lambda raw: base64.b64encode(raw).decode('ascii')
    result = {
        'sourceTask': task,
        'sourceSha256': digest,
        'sourceTextureResolution': list(tex.size),
        'atlasResolution': [texture_size, texture_size],
        'triangles': len(indices),
        'vertices': len(vertices),
        'bounds': np.round(mesh.bounds, 6).tolist(),
        'parts': [{
            'part': kind,
            'pivot': [0, 0, 0],
            'positions': enc(pos16.tobytes()),
            'uv': enc(uv16.tobytes()),
            'indices': enc(face16.tobytes()),
        }],
        'texture': 'data:image/webp;base64,' + enc(texture_bytes),
    }
    return result, {'part':kind,'triangles':len(indices),'vertices':len(vertices),'atlasBytes':len(texture_bytes),'originalBytes':source.stat().st_size,'sourceSha256':digest,'sourceTexture':list(tex.size),'embeddedTexture':[texture_size,texture_size]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sources',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--texture-size',type=int,default=1024)
    args = parser.parse_args()
    if args.texture_size not in [512,1024,2048]:
        parser.error('texture-size must be 512, 1024 or 2048')
    args.output.mkdir(parents=True,exist_ok=True)
    reports=[]
    for kind in TASKS:
        source=args.sources / (kind+'.glb')
        data, report=encode(kind,source,args.texture_size)
        content='// Generated by scripts/import-meshy-t01.py from the SHA-pinned original Meshy textured GLB.\n' + '// prettier-ignore\n' + 'export const MODEL_DATA = ' + json.dumps(data,separators=(',',':'))+';\n'
        path=args.output/('meshy-t01-'+kind+'-data.js')
        path.write_text(content,encoding='utf8')
        reports.append({**report,'output':str(path),'outputBytes':path.stat().st_size})
    print(json.dumps(reports,indent=2))

if __name__=='__main__':main()
